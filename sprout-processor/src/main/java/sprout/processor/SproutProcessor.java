package sprout.processor;

import java.io.IOException;
import java.io.Writer;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;

/**
 * Build-time DI wiring — Spring Boot's AOT idea, shrunk to the essentials.
 *
 * <p>Scans {@code @Service} classes and {@code @Autowired} fields and generates
 * {@code sprout.generated.SproutBoot}, which builds an {@link sprout.AppContext}
 * with every service provided and injects {@code @Autowired} fields. No runtime
 * reflection — everything is plain generated Java, which is why it works under
 * TeaVM.
 *
 * <p>ponytail: {@code @Autowired} fields must be non-private (generated code sets
 * them directly). Services are wired by field injection, so no constructor
 * ordering / topological sort is needed. Add per-package injectors if you ever
 * want private fields, and constructor injection if a service needs args.
 */
@SupportedAnnotationTypes("*")   // invoked every round, so we can generate in the first one
@SupportedSourceVersion(SourceVersion.RELEASE_17)
public class SproutProcessor extends AbstractProcessor {

    private final List<String> services = new ArrayList<>();                       // service FQNs
    private final Map<String, List<String[]>> autowired = new LinkedHashMap<>();   // owner FQN -> [field, type]
    private boolean generated = false;

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        if (generated) {
            return false;
        }

        TypeElement service = processingEnv.getElementUtils().getTypeElement("sprout.Service");
        TypeElement autowire = processingEnv.getElementUtils().getTypeElement("sprout.Autowired");

        if (service != null) {
            for (Element e : roundEnv.getElementsAnnotatedWith(service)) {
                if (e.getKind() == ElementKind.CLASS) {
                    String fqn = ((TypeElement) e).getQualifiedName().toString();
                    if (!services.contains(fqn)) {
                        services.add(fqn);
                    }
                }
            }
        }
        if (autowire != null) {
            for (Element e : roundEnv.getElementsAnnotatedWith(autowire)) {
                if (e.getKind() != ElementKind.FIELD) {
                    continue;
                }
                VariableElement field = (VariableElement) e;
                if (!field.getModifiers().contains(Modifier.PUBLIC)) {
                    processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                            "@Autowired field must be public — generated SproutBoot sets it directly "
                                    + "(no reflection, and it lives in a different package)", field);
                    continue;
                }
                String owner = ((TypeElement) field.getEnclosingElement()).getQualifiedName().toString();
                autowired.computeIfAbsent(owner, k -> new ArrayList<>())
                        .add(new String[]{field.getSimpleName().toString(), typeName(field.asType())});
            }
        }

        // Generate in the first round, while the hand-written sources (all our
        // @Service / @Autowired live there) are available and BEFORE javac tries
        // to resolve Main's reference to SproutBoot. Generating in the final
        // round is too late — the class would never be compiled.
        if (!roundEnv.processingOver()) {
            write();
            generated = true;
        }
        return false;
    }

    private void write() {
        try {
            JavaFileObject file = processingEnv.getFiler().createSourceFile("sprout.generated.SproutBoot");
            try (Writer w = file.openWriter()) {
                w.write("package sprout.generated;\n\n");
                w.write("// Generated by SproutProcessor — do not edit.\n");
                w.write("public final class SproutBoot {\n");
                w.write("    private SproutBoot() {}\n\n");

                w.write("    /** Build the application context: scan @Service beans, wire @Autowired fields. */\n");
                w.write("    public static sprout.AppContext context() {\n");
                w.write("        sprout.AppContext ctx = new sprout.AppContext();\n");
                List<String> vars = new ArrayList<>();
                for (int i = 0; i < services.size(); i++) {
                    String fqn = services.get(i);
                    String var = "b" + i;
                    vars.add(var);
                    w.write("        " + fqn + " " + var + " = new " + fqn + "();\n");
                    w.write("        ctx.provide(" + fqn + ".class, " + var + ");\n");
                }
                w.write("        sprout.Sprout.setInjector(SproutBoot::inject);\n");
                for (String var : vars) {
                    w.write("        inject(" + var + ", ctx);\n");   // services may @Autowired each other
                }
                w.write("        return ctx;\n");
                w.write("    }\n\n");

                w.write("    /** Set @Autowired fields on a freshly created bean/component. */\n");
                w.write("    public static void inject(Object bean, sprout.AppContext ctx) {\n");
                for (Map.Entry<String, List<String[]>> en : autowired.entrySet()) {
                    String owner = en.getKey();
                    w.write("        if (bean instanceof " + owner + ") {\n");
                    w.write("            " + owner + " t = (" + owner + ") bean;\n");
                    for (String[] f : en.getValue()) {
                        w.write("            t." + f[0] + " = ctx.get(" + f[1] + ".class);\n");
                    }
                    w.write("        }\n");
                }
                w.write("    }\n");
                w.write("}\n");
            }
        } catch (IOException ex) {
            processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, "SproutBoot generation failed: " + ex);
        }
    }

    private static String typeName(TypeMirror t) {
        if (t instanceof DeclaredType) {
            return ((TypeElement) ((DeclaredType) t).asElement()).getQualifiedName().toString();
        }
        return t.toString();
    }
}
